import AppKit
import ImageIO
import UniformTypeIdentifiers

enum ClipboardReadError: LocalizedError {
    case tooLarge
    case invalidImage
    case unreadableFile

    var errorDescription: String? {
        switch self {
        case .tooLarge: "Skipped content exceeding the 20 MiB or 50-megapixel limit."
        case .invalidImage: "The copied image could not be decoded."
        case .unreadableFile: "The copied image file could not be read."
        }
    }
}

enum ClipboardSnapshot: Sendable {
    case text(String)
    case image(Data, type: String)
    case imageFile(URL)

    func makeEntry() throws -> ClipboardEntry {
        switch self {
        case .text(let text):
            guard text.utf8.count <= HistoryStore.maximumEntryBytes else {
                throw ClipboardReadError.tooLarge
            }
            return ClipboardEntry(content: .text(text))
        case .image(let data, let type):
            return try Self.imageEntry(data: data, type: type)
        case .imageFile(let url):
            let values = try url.resourceValues(forKeys: [.fileSizeKey, .isRegularFileKey])
            guard values.isRegularFile == true else { throw ClipboardReadError.unreadableFile }
            guard let size = values.fileSize, size <= HistoryStore.maximumEntryBytes else {
                throw ClipboardReadError.tooLarge
            }
            let data = try Data(contentsOf: url)
            return try Self.imageEntry(data: data, type: nil)
        }
    }

    private static func imageEntry(data: Data, type: String?) throws -> ClipboardEntry {
        guard data.count <= HistoryStore.maximumEntryBytes else {
            throw ClipboardReadError.tooLarge
        }
        guard
            let source = CGImageSourceCreateWithData(
                data as CFData, [kCGImageSourceShouldCache: false] as CFDictionary
            ), let sourceType = CGImageSourceGetType(source),
            let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
            let width = properties[kCGImagePropertyPixelWidth] as? Int,
            let height = properties[kCGImagePropertyPixelHeight] as? Int,
            width > 0, height > 0
        else { throw ClipboardReadError.invalidImage }

        guard width <= 50_000_000 / height else { throw ClipboardReadError.tooLarge }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceThumbnailMaxPixelSize: 160,
            kCGImageSourceCreateThumbnailWithTransform: true,
        ]
        guard let preview = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary),
            let output = CFDataCreateMutable(nil, 0),
            let destination = CGImageDestinationCreateWithData(output, UTType.png.identifier as CFString, 1, nil)
        else { throw ClipboardReadError.invalidImage }
        CGImageDestinationAddImage(destination, preview, nil)
        guard CGImageDestinationFinalize(destination) else { throw ClipboardReadError.invalidImage }
        return ClipboardEntry(
            content: .image(
                data: data, type: type ?? (sourceType as String), thumbnail: output as Data,
                width: width, height: height
            ))
    }
}

@MainActor
enum ClipboardReader {
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]
    private static let imageTypes = [UTType.png, .tiff, .jpeg, .heic, .gif, .bmp]
        .map { NSPasteboard.PasteboardType($0.identifier) }

    static func snapshot(from pasteboard: NSPasteboard) throws -> ClipboardSnapshot? {
        guard let types = pasteboard.types,
            ignoredTypes.isDisjoint(with: types.map(\.rawValue)),
            let items = pasteboard.pasteboardItems, items.count == 1,
            let item = items.first
        else { return nil }

        if let file = item.string(forType: .fileURL), let url = URL(string: file), url.isFileURL {
            guard let type = UTType(filenameExtension: url.pathExtension), type.conforms(to: .image) else {
                return nil
            }
            return .imageFile(url)
        }
        for type in imageTypes where item.types.contains(type) {
            if let data = item.data(forType: type) {
                guard data.count <= HistoryStore.maximumEntryBytes else { throw ClipboardReadError.tooLarge }
                return .image(data, type: type.rawValue)
            }
        }
        if let text = item.string(forType: .string), !text.isEmpty {
            guard text.utf8.count <= HistoryStore.maximumEntryBytes else { throw ClipboardReadError.tooLarge }
            return .text(text)
        }
        return nil
    }
}
