import Foundation

struct CheckFailure: Error, CustomStringConvertible {
    let message: String
    var description: String { message }
}

func expect(
    _ condition: @autoclosure () throws -> Bool,
    file: StaticString = #fileID, line: UInt = #line
) throws {
    if try !condition() { throw CheckFailure(message: "Expectation failed at \(file):\(line)") }
}

func require<Value>(
    _ value: Value?, file: StaticString = #fileID, line: UInt = #line
) throws -> Value {
    guard let value else { throw CheckFailure(message: "Missing value at \(file):\(line)") }
    return value
}

func expect<Failure: Error>(throws type: Failure.Type, _ body: () throws -> Void) throws {
    do { try body() } catch is Failure { return }
    throw CheckFailure(message: "Expected an error of type \(type)")
}

